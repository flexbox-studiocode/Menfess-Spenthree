import { act, render, screen, within } from "@testing-library/react";
import userEvent from "@testing-library/user-event";
import { MemoryRouter } from "react-router-dom";
import { afterEach, beforeEach, describe, it, expect, vi } from "vitest";
import App from "./App.jsx";
import { DRAFT_KEY, readDraft, saveDraft } from "./services/index.js";
import { getSupabaseClient } from "./lib/supabase.js";

vi.mock("./lib/supabase.js", () => ({ getSupabaseClient: vi.fn() }));
vi.mock("./lib/supabaseConfig.js", () => ({ readSupabaseConfig: vi.fn(() => ({ url: "https://example.supabase.co", key: "sb_publishable_test" })) }));
const invoke = vi.fn();
const draft = { category: "aspirasi", recipient: "OSIS Spenthree", content: "Tolong tambahkan tempat membaca di taman sekolah.", rules_accepted: true };
const renderRoute = path => render(<MemoryRouter initialEntries={[path]} useTransitions={false}><App /></MemoryRouter>);
afterEach(() => { vi.useRealTimers(); vi.unstubAllGlobals(); });
beforeEach(() => {
  sessionStorage.clear(); invoke.mockReset();
  getSupabaseClient.mockReturnValue({ functions: { invoke } });
});

describe("preserved menfess integration", () => {
  it("polls the submitted tracking code independently from response and input edits", async () => {
    const user = userEvent.setup();
    invoke.mockResolvedValueOnce({ data: { status: "queued", web_status: "visible", moderation_status: "pending", delivery_status: "queued", message: "Tampil di website" }, error: null });
    invoke.mockResolvedValue({ data: { status: "published", web_status: "hidden", moderation_status: "approved", delivery_status: "published", message: "Status diperbarui" }, error: null });
    renderRoute("/status");
    await user.type(screen.getByLabelText("Kode pelacakan"), "SPT-poll");
    await user.click(screen.getByRole("button", { name: "Periksa status" }));
    expect(await screen.findByText("Website: tampil di linimasa")).toBeInTheDocument();
    expect(screen.getByText("Instagram: menunggu pemeriksaan dan pengiriman")).toBeInTheDocument();
    await user.clear(screen.getByLabelText("Kode pelacakan"));
    await user.type(screen.getByLabelText("Kode pelacakan"), "SPT-not-submitted");
    await act(async () => { document.dispatchEvent(new Event("visibilitychange")); });
    expect(invoke.mock.calls.at(-1)[1].body).toEqual({ tracking_code: "SPT-poll" });
    expect(await screen.findByText("Website: tidak tampil di linimasa")).toBeInTheDocument();
    // Published IG does not end website-status refreshes.
    await act(async () => { document.dispatchEvent(new Event("visibilitychange")); });
    expect(invoke).toHaveBeenCalledTimes(3);
    expect(screen.getByText("SPT-poll")).toBeInTheDocument();
  });
  it("stops the polling interval at a terminal delivery status but keeps visibility refresh", async () => {
    const user = userEvent.setup();
    invoke.mockResolvedValue({ data: { status: "queued", delivery_status: "queued", web_status: "visible" }, error: null });
    renderRoute("/status");
    await user.type(screen.getByLabelText("Kode pelacakan"), "SPT-interval");
    await user.click(screen.getByRole("button", { name: "Periksa status" }));
    await screen.findByText("Website: tampil di linimasa");
    vi.useFakeTimers();
    // Reinstall the active interval under fake timers through a fresh status.
    invoke.mockResolvedValue({ data: { status: "processing", delivery_status: "processing", web_status: "visible" }, error: null });
    await act(async () => { document.dispatchEvent(new Event("visibilitychange")); });
    invoke.mockClear();
    invoke.mockResolvedValue({ data: { status: "published", delivery_status: "published", web_status: "visible" }, error: null });
    await act(async () => { await vi.advanceTimersByTimeAsync(15000); });
    expect(invoke).toHaveBeenCalledTimes(1);
    await act(async () => { await vi.advanceTimersByTimeAsync(30000); });
    expect(invoke).toHaveBeenCalledTimes(1);
    await act(async () => { document.dispatchEvent(new Event("visibilitychange")); });
    expect(invoke).toHaveBeenCalledTimes(2);
  });
  it("does not infer website publication from a legacy queued receipt", async () => {
    const user = userEvent.setup(); saveDraft(draft);
    invoke.mockResolvedValueOnce({ data: { status: "pending_moderation", web_status: "hidden", moderation_status: "pending", delivery_status: null, tracking_code: "SPT-legacy" }, error: null });
    renderRoute("/review");
    expect(screen.getByText(/Publikasi Instagram menunggu pemeriksaan AI/)).toBeInTheDocument();
    await user.click(screen.getByRole("button", { name: "Kirim Menfess" }));
    expect(await screen.findByText("Website: tidak tampil di linimasa")).toBeInTheDocument();
    expect(screen.getByText("Instagram: belum dikirim")).toBeInTheDocument();
    expect(screen.queryByRole("link", { name: "Lihat menfess" })).not.toBeInTheDocument();
  });
  it("tracks a queued receipt without discarding the response when pending status clears", async () => {
    const user = userEvent.setup(); saveDraft(draft);
    invoke.mockResolvedValueOnce({ data: { status: "queued", tracking_code: "SPT-test", message: "Diterima" }, error: null });
    renderRoute("/review");
    await user.click(screen.getByRole("button", { name: "Kirim Menfess" }));
    await screen.findByRole("heading", { name: "Status pesan" });
    invoke.mockResolvedValueOnce({ data: { status: "published", published_at: "2026-10-22T00:00:00Z", ig_permalink: "https://www.instagram.com/p/synthetic/", message: "Sudah diterbitkan" }, error: null });
    await user.type(screen.getByLabelText("Kode pelacakan"), "SPT-test");
    await user.click(screen.getByRole("button", { name: "Periksa status" }));
    expect(await screen.findByRole("link", { name: /Buka Instagram/ })).toHaveAttribute("href", "https://www.instagram.com/p/synthetic/");
  });
  it("uses a new request ID only when an attempted payload changes", async () => {
    const user = userEvent.setup(); saveDraft({ ...draft, request_id: "old-request-id" });
    renderRoute("/write");
    await user.clear(screen.getByLabelText("Isi pesan"));
    await user.type(screen.getByLabelText("Isi pesan"), "Tolong tambah koleksi buku di perpustakaan.");
    await user.click(screen.getByRole("button", { name: "Periksa pesan" }));
    expect(readDraft()).not.toHaveProperty("request_id");
    expect(readDraft().content).toContain("koleksi buku");
  });
  it.each([false, true])("focuses the first invalid field with reduced motion = %s", async reduced => {
    const scrollIntoView = vi.fn();
    vi.stubGlobal("matchMedia", vi.fn(() => ({ matches: !reduced })));
    const user = userEvent.setup(); renderRoute("/write");
    const recipient = screen.getByLabelText(/Untuk/);
    const content = screen.getByLabelText("Isi pesan");
    const agreement = screen.getByRole("checkbox");
    for (const field of [recipient, content, agreement]) field.scrollIntoView = scrollIntoView;
    await user.click(recipient); await user.paste("a".repeat(81));
    await user.click(screen.getByRole("button", { name: "Periksa pesan" }));
    expect(recipient).toHaveFocus();
    expect(recipient).toHaveAttribute("aria-invalid", "true");
    expect(recipient).toHaveAccessibleDescription("Penerima maksimal 80 karakter.");
    await user.clear(recipient);
    await user.click(screen.getByRole("button", { name: "Periksa pesan" }));
    expect(content).toHaveFocus();
    expect(content).toHaveAccessibleDescription(expect.stringContaining("10–500"));
    await user.type(content, draft.content);
    await user.click(screen.getByRole("button", { name: "Periksa pesan" }));
    expect(agreement).toHaveFocus();
    expect(agreement).toHaveAttribute("aria-invalid", "true");
    expect(scrollIntoView).toHaveBeenCalledTimes(3);
    expect(scrollIntoView).toHaveBeenLastCalledWith({ block: "center", behavior: reduced ? "auto" : "smooth" });
    expect(invoke).not.toHaveBeenCalled();
  });
  it("validates, saves a draft, and opens review without sending", async () => {
    const user = userEvent.setup(); renderRoute("/write");
    await user.click(screen.getByRole("button", { name: "Periksa pesan" }));
    expect(screen.getByRole("alert")).toHaveTextContent("10–500");
    await user.selectOptions(screen.getByLabelText("Kategori"), "aspirasi");
    await user.type(screen.getByLabelText(/Untuk/), draft.recipient);
    await user.type(screen.getByLabelText("Isi pesan"), draft.content);
    await user.click(screen.getByRole("button", { name: "Periksa pesan" }));
    expect(screen.getByRole("alert")).toHaveTextContent("Setujui");
    await user.click(screen.getByRole("checkbox"));
    await user.click(screen.getByRole("button", { name: "Periksa pesan" }));
    expect(screen.getByRole("heading", { name: "Periksa pesan" })).toBeInTheDocument();
    expect(readDraft()).toEqual(draft); expect(invoke).not.toHaveBeenCalled();
  });
  it("retains request_id on failure and retry, clears draft only on success", async () => {
    const user = userEvent.setup(); saveDraft(draft);
    let finish;
    invoke.mockRejectedValueOnce(new TypeError("Failed to fetch"));
    invoke.mockImplementationOnce(() => new Promise(resolve => { finish = resolve; }));
    renderRoute("/review");
    await user.click(screen.getByRole("button", { name: "Kirim Menfess" }));
    await screen.findByRole("alert");
    const payload = invoke.mock.calls[0][1].body;
    expect(payload).toMatchObject(draft);
    expect(payload.request_id).toMatch(/^[\da-f-]{36}$/);
    expect(readDraft()).toEqual(payload);
    await user.click(screen.getByRole("button", { name: "Kirim Menfess" }));
    expect(screen.getByRole("button", { name: "Mengirim pesan..." })).toBeDisabled();
    expect(screen.getByRole("button", { name: "Mengirim pesan..." })).toHaveAttribute("aria-busy", "true");
    expect(invoke.mock.calls[1][1].body).toEqual(payload);
    finish({ data: { accepted: true, status: "published", tracking_code: "SPT-0123456789ABCDEF0123456789ABCDEF", message: "Pesan tersimpan." }, error: null });
    await screen.findByRole("heading", { name: "Status pesan" });
    expect(sessionStorage.getItem(DRAFT_KEY)).toBeNull();
    expect(screen.getByText("SPT-0123456789ABCDEF0123456789ABCDEF")).toBeInTheDocument();
    expect(screen.getByText("Instagram: telah diterbitkan")).toBeInTheDocument();
    expect(screen.queryByRole("link", { name: /Buka Instagram/ })).not.toBeInTheDocument();
    expect(screen.getByText("Menfess berhasil dikirim")).toBeInTheDocument();
  });
  it("shows missing draft and returns to writing", async () => {
    const user = userEvent.setup(); renderRoute("/review");
    expect(screen.getByText("Belum ada draf untuk diperiksa.")).toBeInTheDocument();
    await user.click(screen.getByRole("link", { name: "Tulis pesan" }));
    expect(screen.getByRole("textbox", { name: "Isi pesan" })).toBeInTheDocument();
  });
  it("requires review consent and keeps the draft when editing", async () => {
    const user = userEvent.setup(); saveDraft(draft); renderRoute("/review");
    await user.click(screen.getByRole("checkbox"));
    expect(screen.getByRole("button", { name: "Kirim Menfess" })).toBeDisabled();
    expect(readDraft().rules_accepted).toBe(false);
    await user.click(screen.getByRole("button", { name: "Ubah Pesan" }));
    expect(screen.getByLabelText("Isi pesan")).toHaveValue(draft.content);
    expect(screen.getByLabelText(/Untuk/)).toHaveValue(draft.recipient);
    expect(screen.getByLabelText("Kategori")).toHaveValue("aspirasi");
    expect(invoke).not.toHaveBeenCalled();
  });
  it("handles clipboard refusal without losing the receipt", async () => {
    const user = userEvent.setup(); saveDraft(draft);
    invoke.mockResolvedValue({ data: { status: "queued", tracking_code: "SPT-test", message: "Diterima" }, error: null });
    renderRoute("/review");
    await user.click(screen.getByRole("button", { name: "Kirim Menfess" }));
    await screen.findByRole("button", { name: "Salin kode" });
    vi.spyOn(navigator.clipboard, "writeText").mockRejectedValue(new Error("Denied"));
    await user.click(screen.getByRole("button", { name: "Salin kode" }));
    expect(await screen.findByRole("alert")).toHaveTextContent("secara manual");
    expect(screen.getByText("SPT-test")).toBeInTheDocument();
  });
  it("confirms copying only after the clipboard succeeds", async () => {
    const user = userEvent.setup(); saveDraft(draft);
    invoke.mockResolvedValue({ data: { status: "queued", tracking_code: "SPT-copy", message: "Diterima" }, error: null });
    renderRoute("/review");
    await user.click(screen.getByRole("button", { name: "Kirim Menfess" }));
    await user.click(await screen.findByRole("button", { name: "Salin kode" }));
    expect(await screen.findByRole("button", { name: /Tersalin/ })).toBeInTheDocument();
    expect(await navigator.clipboard.readText()).toBe("SPT-copy");
  });
  it("marks character limits without blocking typing or changing Unicode counting", async () => {
    const user = userEvent.setup(); renderRoute("/write");
    await user.click(screen.getByLabelText("Isi pesan"));
    await user.paste("😀".repeat(449));
    expect(screen.getByText("449/500")).toHaveAttribute("data-limit", "normal");
    await user.type(screen.getByLabelText("Isi pesan"), "😀");
    expect(screen.getByText("450/500")).toHaveAttribute("data-limit", "near");
    await user.paste("😀".repeat(50));
    expect(screen.getByText("500/500")).toHaveAttribute("data-limit", "near");
    await user.type(screen.getByLabelText("Isi pesan"), "😀");
    expect(screen.getByText("501/500")).toHaveAttribute("data-limit", "over");
    await user.click(screen.getByRole("button", { name: "Periksa pesan" }));
    expect(screen.getByRole("alert")).toHaveTextContent("10–500");
    expect(invoke).not.toHaveBeenCalled();
  });
  it("tracks with the existing POST contract and real publication fields", async () => {
    const user = userEvent.setup();
    invoke.mockResolvedValue({ data: { status: "published", message: "Pesan berhasil dipublikasikan.", published_at: "2026-10-21T10:00:00Z", ig_permalink: "https://www.instagram.com/p/example/" }, error: null });
    renderRoute("/status");
    await user.type(screen.getByLabelText("Kode pelacakan"), "SPT-0123456789ABCDEF0123456789ABCDEF");
    await user.click(screen.getByRole("button", { name: "Periksa status" }));
    await screen.findByText("Pesan berhasil dipublikasikan.");
    expect(invoke).toHaveBeenCalledWith("track-menfess", expect.objectContaining({ body: { tracking_code: "SPT-0123456789ABCDEF0123456789ABCDEF" } }));
    expect(screen.getByRole("link", { name: /Buka Instagram/ })).toHaveAttribute("href", "https://www.instagram.com/p/example/");
    expect(screen.queryByText("Ditanggapi OSIS")).not.toBeInTheDocument();
  });
  it("shows tracking errors and allows retry", async () => {
    const user = userEvent.setup();
    invoke.mockResolvedValue({ data: null, error: { context: { status: 404, json: async () => ({ error: { code: "NOT_FOUND" } }) } } });
    renderRoute("/status"); await user.type(screen.getByLabelText("Kode pelacakan"), "SPT-test");
    await user.click(screen.getByRole("button", { name: "Periksa status" }));
    expect(await screen.findByRole("alert")).toHaveTextContent("tidak ditemukan");
    expect(screen.getByRole("button", { name: "Periksa status" })).toBeEnabled();
  });
  it("counts Unicode code points and normalizes a valid emoji draft", async () => {
    const user = userEvent.setup(); renderRoute("/write");
    await user.type(screen.getByLabelText("Isi pesan"), "😀".repeat(6));
    await user.click(screen.getByRole("checkbox"));
    await user.click(screen.getByRole("button", { name: "Periksa pesan" }));
    expect(screen.getByRole("alert")).toHaveTextContent("10–500");
    await user.clear(screen.getByLabelText("Isi pesan"));
    await user.type(screen.getByLabelText("Isi pesan"), "😀".repeat(10));
    await user.click(screen.getByRole("button", { name: "Periksa pesan" }));
    expect(readDraft().content).toBe("😀".repeat(10));
    expect(invoke).not.toHaveBeenCalled();
  });
  it("loads and filters an empty published feed without direct table access", async () => {
    const user = userEvent.setup();
    const fetchMock = vi.fn().mockResolvedValue({ ok: true, json: async () => ({ data: [], next_cursor: null }) });
    vi.stubGlobal("fetch", fetchMock); renderRoute("/");
    expect(await screen.findByText("Belum ada menfess di linimasa")).toBeInTheDocument();
    await user.click(screen.getByRole("button", { name: "Aspirasi", exact: true }));
    expect(screen.getByRole("button", { name: "Aspirasi", exact: true })).toHaveAttribute("aria-pressed", "true");
    await screen.findByText("Belum ada menfess di linimasa");
    expect(fetchMock.mock.calls.at(-1)[0].searchParams.get("category")).toBe("aspirasi");
    expect(invoke).not.toHaveBeenCalled();
    await user.click(within(screen.getByRole("status")).getByRole("link", { name: "Tulis menfess" }));
    expect(screen.getByRole("heading", { name: "Tulis menfess" })).toBeInTheDocument();
  });
});
